export function getCssFilterString(filter: FilterPreset, manualBrightness = 0, manualContrast = 0): string {
  const b = Math.max(20, Math.min(250, filter.brightness + manualBrightness));
  const c = Math.max(20, Math.min(250, filter.contrast + manualContrast));
  const g = filter.grayscale;
  const s = filter.sepia;
  const sat = filter.saturate;
  const inv = filter.invert;
  const hue = filter.hueRotate;

  return `brightness(${b}%) contrast(${c}%) grayscale(${g}%) sepia(${s}%) saturate(${sat}%) invert(${inv}%) hue-rotate(${hue}deg)`;
}
